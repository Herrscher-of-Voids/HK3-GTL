/**
 * 研究节点分类枚举 —— 用于 GUI 分组 / 图标 / 颜色区分，以及某些门槛策略的判别。
 *
 * <h3>修改指南</h3>
 * <ul>
 *   <li>新增类型：在末尾追加枚举值（勿插入中间，避免影响依赖 ordinal 的序列化）</li>
 *   <li>新增类型后需同步：
 *     <ul>
 *       <li>GUI 分类 Tab（客户端研究界面）</li>
 *       <li>语言文件中的 {@code hk3gtl.research.type.<名称小写>} 翻译键</li>
 *       <li>（可选）为该类型分配专属图标资源</li>
 *     </ul>
 *   </li>
 *   <li>枚举顺序可作为 GUI 默认排序依据，调整前确认所有引用方的排序假设</li>
 * </ul>
 */
public enum Hk3ResearchType {
    /** 理论研究：纯知识节点，通常靠前置解锁而非物品提交。 */
    THEORY,
    /** 材料研究：与新材料、新中间件相关的节点。 */
    MATERIAL,
    /** 电压研究：推进到下一电压档所需的节点（与 GT 电压阶梯绑定）。 */
    VOLTAGE,
    /** 电路研究：解锁新电路 / 处理器层级的节点。 */
    CIRCUIT,
    /** 结构研究：与多方块结构成型相关的节点（如新机器解锁）。 */
    STRUCTURE,
    /** 事件研究：由事件触发自动完成的节点（不需要手动提交）。 */
    EVENT,
    /** 认证研究：终末 / 阶段性认证节点，通常作为大阶段解锁的门槛。 */
    CERTIFICATION
}
