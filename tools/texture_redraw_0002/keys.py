def canvas():
    im = Image.new('RGBA', (64, 64))
    return im, ImageDraw.Draw(im)


def facet(im, points, color, seed, amount=10):
    d = ImageDraw.Draw(im)
    d.polygon(points, fill=color)
    mask = Image.new('1', im.size)
    ImageDraw.Draw(mask).polygon(points, fill=1)
    rng = Random(seed)
    rgb = tuple(bytes.fromhex(color[1:]))
    for _ in range(amount):
        x, y = rng.randint(0, 63), rng.randint(0, 63)
        if mask.getpixel((x, y)):
            step = rng.choice((-13, -8, 8, 12))
            shade = tuple(max(0, min(255, c + step)) for c in rgb)
            d.point((x, y), fill=shade)
            if mask.getpixel((min(x + 1, 63), y)):
                d.point((x + 1, y), fill=shade)


